// CRM-only notification data model.
// Fully isolated from the app's global notification system (services/notifications.ts,
// components/NotificationBell.tsx, Firebase path `notifications/*`). Everything here lives
// under the separate `crm/notifications/feed` Firebase path.

/** Which CRM tab / Firebase path a notification was generated from. */
export type CrmNotificationSourceTab =
  | "yetToHappen"
  | "leads"
  | "callBackSendInfo"
  | "keepInTouch"
  | "whatsapp"
  | "linkedin"
  // CRM Core Domain (crm/meetings, crm/followups, crm/opportunities, crm/quotations) —
  // additive sources, generated by `domain/domainNotificationService.ts` into this same feed.
  | "domainMeetings"
  | "domainFollowUps"
  | "domainOpportunities"
  | "domainQuotations";

/** What kind of CRM activity triggered the notification. */
export type CrmNotificationType =
  | "meeting-tomorrow"
  | "meeting-today"
  | "meeting-overdue"
  | "followup-due"
  | "followup-overdue"
  | "callback-due"
  | "callback-overdue"
  | "keepintouch-due"
  | "keepintouch-overdue"
  | "whatsapp-followup"
  | "whatsapp-followup-overdue"
  | "linkedin-followup"
  | "linkedin-followup-overdue"
  // CRM Core Domain additions
  | "meeting-rescheduled"
  | "opportunity-stuck"
  | "quotation-pending"
  | "expected-close-near";

/** Action-based workflow state — never a disappearing toast. */
export type CrmNotificationStatus =
  "Pending" | "Acknowledged" | "Done" | "Snoozed" | "Overdue";

export type CrmNotificationPriority = "high" | "medium" | "low";

export interface CrmNotification {
  id: string;
  sourceTab: CrmNotificationSourceTab;
  sourceRowId: string;
  /** Raw text of the due-date field last used to generate this notification — used to detect row edits. */
  sourceDueRaw: string;
  relatedTabLabel: string;
  type: CrmNotificationType;
  title: string;
  description: string;
  companyName?: string;
  /** CRM Core Domain Account id (`crm/accounts/{id}`) this notification is about, when it was
   *  generated from a domain source (`sourceTab` starting with `domain*`). Legacy-sheet-sourced
   *  notifications have no domain Account and leave this unset — `companyName` is their only
   *  identity, and Company 360 keys them by a slug of it instead. */
  accountId?: string;
  prospectName?: string;
  /** ISO yyyy-mm-dd */
  dueDate: string;
  dueTime?: string;
  createdAt: number;
  updatedAt: number;
  status: CrmNotificationStatus;
  priority: CrmNotificationPriority;
  acknowledgedAt?: number;
  completedAt?: number;
  snoozeUntil?: number;
  /** Read/unread indicator — independent of the action `status` above. Defaults to unread. */
  isRead?: boolean;
}

export type CrmNotificationFeed = Record<string, CrmNotification>;

/** A notification moved out of the active feed into the Recycle Bin — never permanently lost. */
export interface CrmDeletedNotification extends CrmNotification {
  deletedAt: number;
  deletedBy?: string;
}

export type CrmNotificationRecycleBin = Record<string, CrmDeletedNotification>;
