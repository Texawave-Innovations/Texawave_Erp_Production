// Phase 12 — deterministic barcode value derivation. Code128 can encode arbitrary printable
// ASCII, so a product's own `productCode` is already a valid Code128 value — nothing to derive.
// EAN-13 can only encode 12 digits + a check digit, so for products that don't have a
// merchandise-style numeric barcode assigned we derive a stable pseudo-GTIN from the productCode
// so the same SKU always renders the same EAN-13, without ever writing back to `sales/products`.

/** Simple, stable string hash (djb2) — used only to derive a deterministic numeric seed. */
function hashString(value: string): number {
  let hash = 5381;
  for (let i = 0; i < value.length; i++) {
    hash = ((hash << 5) + hash + value.charCodeAt(i)) >>> 0;
  }
  return hash >>> 0;
}

/** Computes the standard EAN-13 check digit for a 12-digit payload. */
export function computeEan13CheckDigit(digits12: string): string {
  const digits = digits12.padStart(12, "0").slice(-12).split("").map(Number);
  const sum = digits.reduce((acc, d, i) => acc + d * (i % 2 === 0 ? 1 : 3), 0);
  const check = (10 - (sum % 10)) % 10;
  return String(check);
}

/** Derives a deterministic 13-digit EAN-13 value from an arbitrary product code. Prefixed with
 * "20" (a standard "in-store use" GS1 prefix range) so it's visually distinguishable from a
 * real assigned GTIN. */
export function deriveEan13FromCode(productCode: string): string {
  const seed = hashString(productCode.toUpperCase())
    .toString()
    .padStart(10, "0")
    .slice(0, 10);
  const digits12 = `20${seed}`.slice(0, 12);
  return digits12 + computeEan13CheckDigit(digits12);
}

/** True when a value is already a valid 12 or 13 digit numeric string an EAN-13 can render
 * (the 13th check digit is recomputed either way, so 12 raw digits work too). */
export function isEan13Compatible(value: string): boolean {
  return /^\d{12,13}$/.test(value.trim());
}

export function toEan13(value: string): string {
  const digitsOnly = value.replace(/\D/g, "");
  if (digitsOnly.length >= 12)
    return (
      digitsOnly.slice(0, 12) + computeEan13CheckDigit(digitsOnly.slice(0, 12))
    );
  return deriveEan13FromCode(value);
}

/** The Code128 value for a product — its assigned barcode if set, else its own productCode. */
export function productBarcodeValue(
  productCode: string,
  assignedBarcode?: string,
): string {
  return (assignedBarcode || "").trim() || productCode;
}

/** Firebase-safe-ish sanitizer for values embedded in a printable label id/key. */
export function sanitizeCode(value: string): string {
  return value.trim();
}

