// Structured QR payloads (Phase 12b). A QR code generated by this app encodes a small JSON
// object — `{ scm: 1, type, code, id? }` — instead of a bare string, so scanning it resolves
// straight to one specific record instead of falling through the full multi-entity text search.
// Linear barcodes (Code128/EAN-13) always stay plain text/digits — that's a hardware/format
// constraint, not a choice — so this only applies to QR. Manually-typed or third-party-scanned
// plain-text codes (a raw PO number, a raw location code, ...) keep working exactly as before:
// `resolveScan()` falls back to the ordinary text search whenever the scanned value isn't one of
// these payloads. The `scm: 1` marker exists so an unrelated QR code that happens to contain JSON
// is never misread as one of ours. No sensitive data is ever placed in the payload — only the
// entity type and its existing public code/id, per the Phase 12b spec's "do not put sensitive
// information into QR payloads" rule. */
import type { ScmScanResultType } from "./barcodeTypes";

export interface ScmQrPayload {
  scm: 1;
  type: ScmScanResultType;
  code: string;
  id?: string;
}

export function buildQrPayload(
  type: ScmScanResultType,
  code: string,
  id?: string,
): string {
  const payload: ScmQrPayload = id
    ? { scm: 1, type, code, id }
    : { scm: 1, type, code };
  return JSON.stringify(payload);
}

export function parseQrPayload(raw: string): ScmQrPayload | null {
  const trimmed = raw.trim();
  if (!trimmed.startsWith("{")) return null;
  try {
    const obj = JSON.parse(trimmed);
    if (
      obj &&
      obj.scm === 1 &&
      typeof obj.type === "string" &&
      typeof obj.code === "string"
    )
      return obj as ScmQrPayload;
  } catch {
    // Not JSON — an ordinary plain-text/plain-digit scan, handled by the normal text resolver.
  }
  return null;
}
