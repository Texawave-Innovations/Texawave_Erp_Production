// Phase 12 — the single place a scanned/typed code is turned into an SCM record. Pure functions
// over already-loaded collections (see `barcodeService.ts`'s `useBarcodeMasterData`), matching
// the "no server-side query, fetch-then-filter client-side" convention used by every other SCM
// list page. Never fabricates a result — an unmatched code always resolves to type 'UNKNOWN'.
import type { BarcodeMasterData } from "./barcodeService";
import type { ScmScanResult, ScmScanResultType } from "./barcodeTypes";
import { parseQrPayload, productBarcodeValue } from "./barcodeHelpers";
import { locationLabel } from "../warehouse/warehouseHelpers";

function norm(value: string): string {
  return value.trim().toLowerCase();
}

function eq(a: string | undefined | null, b: string): boolean {
  return !!a && norm(a) === norm(b);
}

/** One matcher per resolvable entity type, in Phase 12 spec section 15's resolution order:
 * 1. Product barcode  2. SKU  3. Batch number  4. Serial number  5. Location code
 * 6. PO number  7. GRN number  8. Sales Order number  9. Shipment/tracking number  10. Return number
 * Reused both by the plain-text search (tries every matcher) and by the structured-QR fast path
 * (Phase 12b — runs only the one matcher the payload's `type` names, see `resolveScan()` below). */
const TYPE_MATCHERS: Record<
  Exclude<ScmScanResultType, "UNKNOWN">,
  (code: string, data: BarcodeMasterData) => ScmScanResult[]
> = {
  PRODUCT: (code, data) => {
    const out: ScmScanResult[] = [];
    for (const product of data.products) {
      const setting = data.settings.find(
        (s) => s.productCode === product.productCode,
      );
      const barcode = productBarcodeValue(
        product.productCode,
        setting?.barcode,
      );
      if (eq(barcode, code) || eq(product.productCode, code))
        out.push(buildProductResult(product, setting?.barcode, data));
    }
    return out;
  },
  SUPPLIER: (code, data) =>
    data.vendors
      .filter((v) => eq(v.vendorCode, code))
      .map((v) => buildSupplierResult(v, data)),
  WAREHOUSE: (code, data) =>
    data.warehouses.filter((w) => eq(w.code, code)).map(buildWarehouseResult),
  BATCH: (code, data) =>
    data.batches
      .filter((b) => eq(b.batchNumber, code))
      .map((b) => buildBatchResult(b, data)),
  SERIAL: (code, data) =>
    data.serials
      .filter((s) => eq(s.serialNumber, code))
      .map((s) => buildSerialResult(s, data)),
  LOCATION: (code, data) =>
    data.locations
      .filter((l) => eq(l.locationCode, code) || eq(l.binCode, code))
      .map((l) => buildLocationResult(l, data)),
  PURCHASE_REQUISITION: (code, data) =>
    data.requisitions
      .filter((r) => eq(r.requisitionNumber, code))
      .map((r) => buildRequisitionResult(r, data)),
  RFQ: (code, data) =>
    data.rfqs
      .filter((r) => eq(r.rfqNumber, code))
      .map((r) => buildRfqResult(r, data)),
  PURCHASE_ORDER: (code, data) =>
    data.purchaseOrders
      .filter((po) => eq(po.poNumber, code))
      .map((po) => buildPoResult(po, data)),
  GRN: (code, data) =>
    data.grns.filter((g) => eq(g.grnNumber, code)).map(buildGrnResult),
  SALES_ORDER: (code, data) =>
    data.salesOrders
      .filter((so) => eq(so.soNumber, code))
      .map(buildSalesOrderResult),
  PICK_LIST: (code, data) =>
    data.pickings
      .filter((p) => eq(p.pickNumber, code))
      .map(buildPickListResult),
  PACKAGE: (code, data) => {
    const out: ScmScanResult[] = [];
    for (const packing of data.packings) {
      for (const pkg of packing.packages || []) {
        if (eq(pkg.packageNumber, code))
          out.push(buildPackageResult(pkg, packing));
      }
    }
    return out;
  },
  SHIPMENT: (code, data) =>
    data.shipments
      .filter(
        (sh) => eq(sh.shipmentNumber, code) || eq(sh.trackingNumber, code),
      )
      .map(buildShipmentResult),
  RETURN: (code, data) =>
    data.returns.filter((r) => eq(r.returnNumber, code)).map(buildReturnResult),
  QC_INSPECTION: (code, data) =>
    data.qcInspections
      .filter((i) => eq(i.inspectionNumber, code))
      .map(buildQcInspectionResult),
  QUARANTINE: (code, data) =>
    data.quarantine
      .filter((q) => eq(q.id, code))
      .map((q) => buildQuarantineResult(q, data)),
};

export function resolveScan(
  rawCode: string,
  data: BarcodeMasterData,
): ScmScanResult {
  const code = rawCode.trim();
  if (!code) return unknownResult(code);

  // Phase 12b structured QR fast path: a QR generated by this app encodes `{scm:1, type, code}` —
  // when present, resolve directly against that one entity type instead of the full text search.
  // Falls through to the ordinary search below if the payload's own code no longer matches
  // anything (e.g. the record was renamed/removed since the label was printed).
  const payload = parseQrPayload(code);
  if (payload && payload.type !== "UNKNOWN") {
    const matcher = TYPE_MATCHERS[payload.type];
    const payloadMatches = matcher ? matcher(payload.code, data) : [];
    if (payloadMatches.length === 1) return payloadMatches[0];
    if (payloadMatches.length > 1)
      return { ...payloadMatches[0], alternatives: payloadMatches };
  }

  const searchCode = payload?.code ?? code;
  const matches: ScmScanResult[] = [];
  for (const matcher of Object.values(TYPE_MATCHERS))
    matches.push(...matcher(searchCode, data));

  if (matches.length === 0) return unknownResult(code);
  if (matches.length === 1) return matches[0];
  return { ...matches[0], alternatives: matches };
}

function unknownResult(code: string): ScmScanResult {
  return {
    type: "UNKNOWN",
    code,
    title: "No SCM record found",
    subtitle:
      "This barcode does not match any product, location, batch, serial or document.",
    fields: [],
  };
}

/** Mirrors `useInventoryData.ts`'s `computeStockStatus()` rule for the two fields a scan result
 * actually has (total available / reorder level) — not reused directly since that function takes
 * a full per-warehouse `InventoryRow`, and a product scan result is a cross-warehouse total. */
function stockStatusFor(
  hasBalance: boolean,
  available: number,
  reorderLevel: number | undefined,
): string {
  if (!hasBalance || available <= 0) return "Out of Stock";
  if (reorderLevel != null && available <= reorderLevel) return "Low Stock";
  if (reorderLevel != null && reorderLevel > 0 && available > reorderLevel * 5)
    return "Overstock";
  return "Healthy";
}

function buildProductResult(
  product: BarcodeMasterData["products"][number],
  assignedBarcode: string | undefined,
  data: BarcodeMasterData,
): ScmScanResult {
  const rows = data.balances.filter(
    (b) => b.productCode === product.productCode,
  );
  const totalOnHand = rows.reduce((s, r) => s + (r.onHand || 0), 0);
  const totalReserved = rows.reduce((s, r) => s + (r.reserved || 0), 0);
  const totalAvailable = rows.reduce(
    (s, r) => s + (r.available ?? (r.onHand || 0) - (r.reserved || 0)),
    0,
  );
  const warehouseNames = rows
    .filter((r) => (r.onHand || 0) > 0)
    .map(
      (r) =>
        data.warehouses.find((w) => w.id === r.warehouseId)?.name ||
        r.warehouseId,
    );
  const setting = data.settings.find(
    (s) => s.productCode === product.productCode,
  );
  const status = stockStatusFor(
    rows.length > 0,
    totalAvailable,
    setting?.reorderLevel,
  );
  return {
    type: "PRODUCT",
    code: productBarcodeValue(product.productCode, assignedBarcode),
    title: product.name,
    subtitle: `SKU ${product.productCode}${product.category ? ` · ${product.category}` : ""}`,
    fields: [
      { label: "SKU", value: product.productCode },
      {
        label: "Barcode",
        value: productBarcodeValue(product.productCode, assignedBarcode),
      },
      { label: "On Hand", value: String(totalOnHand) },
      { label: "Reserved", value: String(totalReserved) },
      { label: "Available", value: String(totalAvailable) },
      {
        label: "Warehouse(s)",
        value: warehouseNames.length ? warehouseNames.join(", ") : "—",
      },
      { label: "Stock Status", value: status },
    ],
    viewPath: `/scm/inventory/overview/${encodeURIComponent(product.productCode)}`,
    viewLabel: "View Inventory",
  };
}

