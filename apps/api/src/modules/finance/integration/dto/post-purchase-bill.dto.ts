import { ApiProperty, ApiPropertyOptional } from "@nestjs/swagger";
import { Type } from "class-transformer";
import {
  IsArray,
  IsBoolean,
  IsDateString,
  IsInt,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  Min,
  ValidateNested,
} from "class-validator";

export class PostPurchaseBillTaxItemDto {
  @ApiPropertyOptional({
    example: "847130",
    description: "HSN or SAC code for this line group",
  })
  @IsOptional()
  @IsString()
  hsnSacCode?: string | null | undefined;

  @ApiProperty({
    example: 10000.0,
    description: "Taxable subtotal for this HSN/rate group in INR",
  })
  @IsNotEmpty()
  @IsNumber()
  @Min(0)
  taxableAmount!: number;

  @ApiPropertyOptional({
    example: 18.0,
    description: "GST tax rate percentage (e.g. 18 for 18%)",
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  taxRate?: number;

  @ApiPropertyOptional({ example: 9.0, description: "CGST rate percentage" })
  @IsOptional()
  @IsNumber()
  @Min(0)
  cgstRate?: number;

  @ApiPropertyOptional({ example: 900.0, description: "CGST amount in INR" })
  @IsOptional()
  @IsNumber()
  @Min(0)
  cgstAmount?: number;

  @ApiPropertyOptional({ example: 9.0, description: "SGST rate percentage" })
  @IsOptional()
  @IsNumber()
  @Min(0)
  sgstRate?: number;

  @ApiPropertyOptional({ example: 900.0, description: "SGST amount in INR" })
  @IsOptional()
  @IsNumber()
  @Min(0)
  sgstAmount?: number;

  @ApiPropertyOptional({ example: 0.0, description: "IGST rate percentage" })
  @IsOptional()
  @IsNumber()
  @Min(0)
  igstRate?: number;

  @ApiPropertyOptional({ example: 0.0, description: "IGST amount in INR" })
  @IsOptional()
  @IsNumber()
  @Min(0)
  igstAmount?: number;

  @ApiProperty({
    example: 1800.0,
    description: "Total tax amount for this line item in INR",
  })
  @IsNotEmpty()
  @IsNumber()
  @Min(0)
  totalTaxAmount!: number;
}

export class PostPurchaseBillDto {
  @ApiProperty({
    example: "TW/BILL/0001",
    description: "Internal bill reference number generated by the ERP",
  })
  @IsNotEmpty()
  @IsString()
  billNumber!: string;

  @ApiPropertyOptional({
    example: "SUPP-INV-9901",
    description: "External invoice number as provided by the vendor",
  })
  @IsOptional()
  @IsString()
  supplierBillNumber?: string | null | undefined;

  @ApiProperty({
    example: "2026-10-15",
    description: "Vendor bill date (YYYY-MM-DD)",
  })
  @IsNotEmpty()
  @IsDateString()
  billDate!: string;

  @ApiPropertyOptional({
    example: 45,
    description: "Supplier database primary key ID",
  })
  @IsOptional()
  @IsInt()
  supplierId?: number | null | undefined;

  @ApiProperty({
    example: "Zenith Components Pvt Ltd",
    description: "Supplier legal/business name",
  })
  @IsNotEmpty()
  @IsString()
  supplierName!: string;

  @ApiPropertyOptional({
    example: "33AAMCT4293K1ZU",
    description: "Supplier 15-character GSTIN if registered",
  })
  @IsOptional()
  @IsString()
  supplierGstin?: string | null | undefined;

  @ApiProperty({
    example: 20000.0,
    description: "Bill taxable subtotal amount before taxes in INR",
  })
  @IsNotEmpty()
  @IsNumber()
  @Min(0.01)
  subtotal!: number;

  @ApiProperty({
    example: 3600.0,
    description: "Bill total tax amount in INR",
  })
  @IsNotEmpty()
  @IsNumber()
  @Min(0)
  taxAmount!: number;

  @ApiProperty({
    example: 23600.0,
    description: "Grand total bill amount (subtotal + taxAmount) in INR",
  })
  @IsNotEmpty()
  @IsNumber()
  @Min(0.01)
  total!: number;

  @ApiPropertyOptional({
    example: "INR",
    description: "ISO currency code (default: INR)",
  })
  @IsOptional()
  @IsString()
  currency?: string;

  @ApiPropertyOptional({
    example: "847130",
    description: "Primary HSN or SAC classification code",
  })
  @IsOptional()
  @IsString()
  hsnSacCode?: string | null | undefined;

  @ApiPropertyOptional({
    example: 9.0,
    description: "CGST tax rate percentage",
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  cgstRate?: number;

  @ApiPropertyOptional({
    example: 1800.0,
    description: "CGST tax component in INR",
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  cgstAmount?: number;

  @ApiPropertyOptional({
    example: 9.0,
    description: "SGST tax rate percentage",
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  sgstRate?: number;

  @ApiPropertyOptional({
    example: 1800.0,
    description: "SGST tax component in INR",
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  sgstAmount?: number;

  @ApiPropertyOptional({
    example: 0.0,
    description: "IGST tax rate percentage",
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  igstRate?: number;

  @ApiPropertyOptional({
    example: 0.0,
    description: "IGST tax component in INR",
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  igstAmount?: number;

  @ApiPropertyOptional({
    type: [PostPurchaseBillTaxItemDto],
    description: "Multi-line tax breakdown grouped by HSN and tax rate",
  })
  @IsOptional()
  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => PostPurchaseBillTaxItemDto)
  taxItems?: PostPurchaseBillTaxItemDto[];

  @ApiPropertyOptional({
    example: true,
    description:
      "Whether the purchase bill is eligible for Input Tax Credit (ITC). If false, tax is incorporated into expense cost.",
  })
  @IsOptional()
  @IsBoolean()
  isItcEligible?: boolean;

  @ApiPropertyOptional({
    example: "Monthly hardware component delivery against PO-0412",
    description: "Bill narration or notes",
  })
  @IsOptional()
  @IsString()
  notes?: string | null | undefined;

  @ApiPropertyOptional({
    example: 8,
    description: "Originating ScmPurchaseOrder primary key ID if applicable",
  })
  @IsOptional()
  @IsInt()
  purchaseOrderId?: number | null | undefined;
}
