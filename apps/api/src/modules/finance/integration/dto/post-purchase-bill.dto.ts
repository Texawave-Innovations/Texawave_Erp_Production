import { ApiProperty, ApiPropertyOptional } from "@nestjs/swagger";
import {
  IsDateString,
  IsInt,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  Min,
} from "class-validator";

export class PostPurchaseBillDto {
  @ApiProperty({
    example: "TW/BILL/0001",
    description: "Internal bill reference number generated by the ERP",
  })
  @IsNotEmpty()
  @IsString()
  billNumber!: string;

  @ApiPropertyOptional({
    example: "SUPP-INV-9901",
    description: "External invoice number as provided by the vendor",
  })
  @IsOptional()
  @IsString()
  supplierBillNumber?: string | null;

  @ApiProperty({
    example: "2026-10-15",
    description: "Vendor bill date (YYYY-MM-DD)",
  })
  @IsNotEmpty()
  @IsDateString()
  billDate!: string;

  @ApiPropertyOptional({
    example: 45,
    description: "Supplier database primary key ID",
  })
  @IsOptional()
  @IsInt()
  supplierId?: number | null;

  @ApiProperty({
    example: "Zenith Components Pvt Ltd",
    description: "Supplier legal/business name",
  })
  @IsNotEmpty()
  @IsString()
  supplierName!: string;

  @ApiPropertyOptional({
    example: "33AAMCT4293K1ZU",
    description: "Supplier 15-character GSTIN if registered",
  })
  @IsOptional()
  @IsString()
  supplierGstin?: string | null;

  @ApiProperty({
    example: 20000.0,
    description: "Bill taxable subtotal amount before taxes in INR",
  })
  @IsNotEmpty()
  @IsNumber()
  @Min(0.01)
  subtotal!: number;

  @ApiProperty({
    example: 3600.0,
    description: "Bill total tax amount in INR",
  })
  @IsNotEmpty()
  @IsNumber()
  @Min(0)
  taxAmount!: number;

  @ApiProperty({
    example: 23600.0,
    description: "Grand total bill amount (subtotal + taxAmount) in INR",
  })
  @IsNotEmpty()
  @IsNumber()
  @Min(0.01)
  total!: number;

  @ApiPropertyOptional({
    example: "INR",
    description: "ISO currency code (default: INR)",
  })
  @IsOptional()
  @IsString()
  currency?: string;

  @ApiPropertyOptional({
    example: "847130",
    description: "Primary HSN or SAC classification code",
  })
  @IsOptional()
  @IsString()
  hsnSacCode?: string | null;

  @ApiPropertyOptional({
    example: 1800.0,
    description: "CGST tax component in INR",
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  cgstAmount?: number;

  @ApiPropertyOptional({
    example: 1800.0,
    description: "SGST tax component in INR",
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  sgstAmount?: number;

  @ApiPropertyOptional({
    example: 0.0,
    description: "IGST tax component in INR",
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  igstAmount?: number;

  @ApiPropertyOptional({
    example: "Monthly hardware component delivery against PO-0412",
    description: "Bill narration or notes",
  })
  @IsOptional()
  @IsString()
  notes?: string | null;

  @ApiPropertyOptional({
    example: 8,
    description: "Originating ScmPurchaseOrder primary key ID if applicable",
  })
  @IsOptional()
  @IsInt()
  purchaseOrderId?: number | null;
}
