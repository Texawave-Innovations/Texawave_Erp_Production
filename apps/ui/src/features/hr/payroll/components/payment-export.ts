/**
 * Exports individual batch's payments to CSV for reconciliation.
 */
export function exportBatchPaymentsCsv(
  batch: PaymentBatch,
  payments: PayrollPayment[],
): void {
  const headers = [
    "Batch #",
    "Employee Code",
    "Employee Name",
    "Bank Name",
    "Account Number",
    "Net Amount (₹)",
    "Payment Method",
    "Payment Status",
    "Bank Reference / UTR",
    "Credited Date",
  ];

  let sumAmount = 0;

  const rows = payments.map((p) => {
    const amt = parseMoney(p.amount);
    sumAmount += amt;

    return [
      safeCell(batch.batchNumber),
      safeCell(p.employee.employeeCode),
      safeCell(p.employee.fullName),
      safeCell(p.employee.bankDetails?.bankName || "—"),
      safeCell(p.employee.bankDetails?.accountNumber || "—"),
      amt.toFixed(2),
      safeCell(p.paymentMethod),
      safeCell(p.status),
      safeCell(p.bankReference || "—"),
      safeCell(p.creditedAt ? isoDate(p.creditedAt) : "—"),
    ].join(",");
  });

  const summaryRow = [
    safeCell("TOTAL"),
    safeCell(`${payments.length} Payments`),
    safeCell(""),
    safeCell(""),
    safeCell(""),
    sumAmount.toFixed(2),
    safeCell(""),
    safeCell(""),
    safeCell(""),
    safeCell(""),
  ].join(",");

  const csvContent =
    "\uFEFF" + [headers.join(","), ...rows, summaryRow].join("\r\n");
  const fileName = `Payment_Batch_${batch.batchNumber}_Reconciliation.csv`;
  downloadText(fileName, csvContent, "text/csv;charset=utf-8");
}

