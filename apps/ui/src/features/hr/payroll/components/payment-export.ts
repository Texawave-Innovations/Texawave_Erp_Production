/** Neutralises dangerous spreadsheet formula injections */
function safeCell(value: string | number | null | undefined): string {
  if (value === null || value === undefined) return '""';
  let s = String(value).trim();
  if (/^[=+\-@\t\r]/.test(s)) {
    s = `'${s}`;
  }
  return `"${s.replace(/"/g, '""')}"`;
}

function parseMoney(val: string | number | null | undefined): number {
  return Number(val ?? 0) || 0;
}

function escapeXml(unsafe: string | number | null | undefined): string {
  if (unsafe === null || unsafe === undefined) return "";
  return String(unsafe)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/**
 * Exports payment batches overview list to CSV.
 */
export function exportPaymentBatchesCsv(batches: PaymentBatch[]): void {
  const headers = [
    "Batch Number",
    "Payroll Period",
    "Total Employees",
    "Total Amount (₹)",
    "Status",
    "Generated Date",
    "Generated By",
    "Processed Date",
  ];

  let sumAmount = 0;
  let sumEmployees = 0;

  const rows = batches.map((b) => {
    const amt = parseMoney(b.totalAmount);
    sumAmount += amt;
    sumEmployees += b.totalEmployees;

    return [
      safeCell(b.batchNumber),
      safeCell(periodLabel(b.payrollPeriod)),
      b.totalEmployees,
      amt.toFixed(2),
      safeCell(b.status),
      safeCell(isoDate(b.generatedAt)),
      safeCell(b.generator?.fullName || "System"),
      safeCell(b.processedAt ? isoDate(b.processedAt) : "—"),
    ].join(",");
  });

  const summaryRow = [
    safeCell("TOTALS"),
    safeCell(`${batches.length} Batches`),
    sumEmployees,
    sumAmount.toFixed(2),
    safeCell(""),
    safeCell(""),
    safeCell(""),
    safeCell(""),
  ].join(",");

  const csvContent =
    "\uFEFF" + [headers.join(","), ...rows, summaryRow].join("\r\n");
  const fileName = `Payment_Batches_Summary_${new Date().toISOString().slice(0, 10)}.csv`;
  downloadText(fileName, csvContent, "text/csv;charset=utf-8");
}

