import { downloadWorkbook } from "@/lib/spreadsheet";
import { downloadText } from "../download";
import { isoDate, periodLabel } from "../format";
import type { PaymentBatch, PayrollPayment } from "../types";

/** Neutralises dangerous spreadsheet formula injections */
function safeCell(value: string | number | null | undefined): string {
  if (value === null || value === undefined) return '""';
  let s = String(value).trim();
  if (/^[=+\-@\t\r]/.test(s)) {
    s = `'${s}`;
  }
  return `"${s.replace(/"/g, '""')}"`;
}

function parseMoney(val: string | number | null | undefined): number {
  return Number(val ?? 0) || 0;
}

/**
 * Exports payment batches overview list to CSV.
 */
export function exportPaymentBatchesCsv(batches: PaymentBatch[]): void {
  const headers = [
    "Batch Number",
    "Payroll Period",
    "Total Employees",
    "Total Amount (₹)",
    "Status",
    "Generated Date",
    "Generated By",
    "Processed Date",
  ];

  let sumAmount = 0;
  let sumEmployees = 0;

  const rows = batches.map((b) => {
    const amt = parseMoney(b.totalAmount);
    sumAmount += amt;
    sumEmployees += b.totalEmployees;

    return [
      safeCell(b.batchNumber),
      safeCell(periodLabel(b.payrollPeriod)),
      b.totalEmployees,
      amt.toFixed(2),
      safeCell(b.status),
      safeCell(isoDate(b.generatedAt)),
      safeCell(b.generator?.fullName || "System"),
      safeCell(b.processedAt ? isoDate(b.processedAt) : "—"),
    ].join(",");
  });

  const summaryRow = [
    safeCell("TOTALS"),
    safeCell(`${batches.length} Batches`),
    sumEmployees,
    sumAmount.toFixed(2),
    safeCell(""),
    safeCell(""),
    safeCell(""),
    safeCell(""),
  ].join(",");

  const csvContent =
    "\uFEFF" + [headers.join(","), ...rows, summaryRow].join("\r\n");
  const fileName = `Payment_Batches_Summary_${new Date().toISOString().slice(0, 10)}.csv`;
  downloadText(fileName, csvContent, "text/csv;charset=utf-8");
}

/**
 * Exports the payment batches overview to a real `.xlsx` workbook.
 */
export async function exportPaymentBatchesExcel(
  batches: PaymentBatch[],
): Promise<void> {
  await downloadWorkbook(
    `Payment_Batches_Summary_${new Date().toISOString().slice(0, 10)}`,
    [
      {
        name: "Payment Batches",
        title: "TexaOne ERP — Payment Batches Summary",
        totals: `TOTALS — ${batches.length} batches`,
        rows: batches,
        columns: [
          { header: "Batch Number", value: (b) => b.batchNumber },
          {
            header: "Payroll Period",
            value: (b) => periodLabel(b.payrollPeriod),
          },
          {
            header: "Employees",
            value: (b) => b.totalEmployees,
            type: "integer",
          },
          {
            header: "Total Amount (₹)",
            value: (b) => parseMoney(b.totalAmount),
            type: "amount",
          },
          { header: "Status", value: (b) => b.status },
          {
            header: "Generated Date",
            value: (b) => b.generatedAt,
            type: "date",
          },
          {
            header: "Generated By",
            value: (b) => b.generator?.fullName || "System",
          },
          {
            header: "Processed Date",
            value: (b) => b.processedAt,
            type: "date",
          },
        ],
      },
    ],
  );
}

/**
 * Exports individual batch's payments to CSV for reconciliation.
 */
export function exportBatchPaymentsCsv(
  batch: PaymentBatch,
  payments: PayrollPayment[],
): void {
  const headers = [
    "Batch #",
    "Employee Code",
    "Employee Name",
    "Bank Name",
    "Account Number",
    "Net Amount (₹)",
    "Payment Method",
    "Payment Status",
    "Bank Reference / UTR",
    "Credited Date",
  ];

  let sumAmount = 0;

  const rows = payments.map((p) => {
    const amt = parseMoney(p.amount);
    sumAmount += amt;

    return [
      safeCell(batch.batchNumber),
      safeCell(p.employee.employeeCode),
      safeCell(p.employee.fullName),
      safeCell(p.employee.bankDetails?.bankName || "—"),
      safeCell(p.employee.bankDetails?.accountNumber || "—"),
      amt.toFixed(2),
      safeCell(p.paymentMethod),
      safeCell(p.status),
      safeCell(p.bankReference || "—"),
      safeCell(p.creditedAt ? isoDate(p.creditedAt) : "—"),
    ].join(",");
  });

  const summaryRow = [
    safeCell("TOTAL"),
    safeCell(`${payments.length} Payments`),
    safeCell(""),
    safeCell(""),
    safeCell(""),
    sumAmount.toFixed(2),
    safeCell(""),
    safeCell(""),
    safeCell(""),
    safeCell(""),
  ].join(",");

  const csvContent =
    "\uFEFF" + [headers.join(","), ...rows, summaryRow].join("\r\n");
  const fileName = `Payment_Batch_${batch.batchNumber}_Reconciliation.csv`;
  downloadText(fileName, csvContent, "text/csv;charset=utf-8");
}

